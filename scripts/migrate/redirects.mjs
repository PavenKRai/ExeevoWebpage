// Generates content/redirects.ts from scripts/migrate/old-urls.txt. Run: node scripts/migrate/redirects.mjs
import { readFile, writeFile } from "node:fs/promises";
import { mapOldPath, typeRoutes } from "./urlmap.mjs";

const urls = (await readFile(new URL("./old-urls.txt", import.meta.url), "utf8")).trim().split("\n");
const patterns = typeRoutes.filter(([from, to]) => from !== to).map(([from, to]) => ({ source: `${from}/:slug`, destination: `${to}/:slug` }));
const isTyped = (p) => typeRoutes.some(([from]) => p.startsWith(from + "/"));
const typeOf = { "/resources/publications/blog": "blog", "/resources/publications/white-papers": "white-papers", "/resources/publications/webinars": "webinars", "/resources/publications/press-releases": "press-releases", "/resources/publications/case-studies": "case-studies", "/resources/analyst-reports": "analyst-reports", "/events": "events", "/glossary": "glossary" };
const kept = {};
for (const t of Object.values(typeOf)) kept[t] = new Set(JSON.parse(await readFile(new URL(`../../content/resources/${t}.json`, import.meta.url), "utf8")).map((r) => r.slug));
const translated = JSON.parse(await readFile(new URL("./translated-map.json", import.meta.url), "utf8"));
const pages = new Map();
let toTwin = 0, toList = 0;
for (const u of urls) {
  const path = new URL(u).pathname.replace(/\/+$/, "") || "/";
  if (path === "/") continue;
  if (isTyped(path)) {
    // Items that were not migrated (translations, non-English) go to their English twin, else the type's list page.
    const [from, to] = typeRoutes.find(([f]) => path.startsWith(f + "/"));
    const type = typeOf[from];
    const raw = path.slice(from.length + 1);
    const slug = decodeURIComponent(raw);
    if (kept[type].has(slug)) continue;
    const twin = translated[type]?.[slug];
    if (twin) toTwin++; else toList++;
    pages.set(path, twin ? `${to}/${twin}` : to);
    continue;
  }
  const to = mapOldPath(path);
  if (!to) throw new Error(`No destination for ${u}`);
  if (to !== path) pages.set(path, to);
}
const body = `// Generated by scripts/migrate/redirects.mjs from the old site's sitemaps. Do not edit by hand.
export type Redirect = { source: string; destination: string; permanent: true };

/** Old content-type URLs: the slug carries over. */
export const contentRedirects: Redirect[] = ${JSON.stringify(patterns.map((r) => ({ ...r, permanent: true })), null, 2)};

/** Old standalone pages (including translated slugs, which go to their English equivalent). */
export const pageRedirects: Redirect[] = ${JSON.stringify([...pages].map(([source, destination]) => ({ source, destination, permanent: true })), null, 2)};
`;
await writeFile(new URL("../../content/redirects.ts", import.meta.url), body);
console.log("patterns", patterns.length, "explicit", pages.size, "(translated items to English twin", toTwin, "to list page", toList + ")");
