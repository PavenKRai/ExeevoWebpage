import type { NextConfig } from "next";
import { contentRedirects, pageRedirects } from "./content/redirects";

/** The old Industries and Solutions by role pages now live on the Platform page as filters. */
const q = (key: string, value: string) => [{ type: "query" as const, key, value }];
const filterRedirects = [
  ...["pharma", "medtech"].map((v) => ({ source: "/industries", has: q("industry", v), destination: `/platform?industry=${v}`, permanent: true })),
  { source: "/industries", destination: "/platform", permanent: true },
  ...["field-rep", "msl", "kam"].map((v) => ({ source: "/solutions-by-role", has: q("role", v), destination: `/platform?role=${v}`, permanent: true })),
  { source: "/solutions-by-role", has: q("role", "consumer-animal-health"), destination: "/platform?industry=consumer-health", permanent: true },
  { source: "/solutions-by-role", destination: "/platform", permanent: true },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  images: { qualities: [75, 90], remotePatterns: [{ protocol: "https", hostname: "cdn.sanity.io" }] },
  // Old exeevo.com (WordPress) URLs -> their new homes. Generated by scripts/migrate/redirects.mjs.
  async redirects() {
    // The old Getting started page is now Professional Services (/getting-started#demo links keep their hash in the browser).
    return [{ source: "/getting-started", destination: "/services", permanent: true }, ...filterRedirects, ...pageRedirects, ...contentRedirects];
  },
};

export default nextConfig;
